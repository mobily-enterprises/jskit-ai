import { readFileSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

// `jskit package nix`, and its part of plain `jskit check`: the app as one Nix package that builds with no network
// access, for a host that runs apps only as Nix packages. package.nix is the same file for every app (it reads
// package.json and package-lock.json while Nix evaluates it), so this writes nothing about the app: it refuses an app
// the file cannot build, and never overwrites a package.nix it did not write. The template is nix/package.nix.in,
// which embeds scripts/nix-app.mjs, the package's programs.

const PACKAGE_NIX_MARKER = "# Generated by `jskit package nix`";
const GUIDE = "https://mobily-enterprises.github.io/jskit-ai/guide/app-setup/package-with-nix";
const TEMPLATE_URL = new URL("../nix/package.nix.in", import.meta.url);
const LAUNCHER_URL = new URL("./nix-app.mjs", import.meta.url);
const REMOTE = /^https?:\/\//u;
const GIT = /^(?:git\+|git:|github:|gitlab:|bitbucket:)/u;

const isObject = (value) => Boolean(value) && typeof value === "object" && !Array.isArray(value);

let rendered = null;

/** The package.nix this release writes, for every app. */
function renderPackageNix() {
  if (rendered === null) {
    // Nix's indented string: '' is written ''' and ${ is written ''${; the indentation every line shares is dropped.
    const launcher = readFileSync(LAUNCHER_URL, "utf8").replace(/\n$/u, "")
      .replace(/''/gu, "'''")
      .replace(/\$\{/gu, "''${")
      .split("\n")
      .map((line) => (line ? `    ${line}` : line))
      .join("\n");
    rendered = readFileSync(TEMPLATE_URL, "utf8")
      .replace("@MARKER@", () => PACKAGE_NIX_MARKER)
      .replace("@LAUNCHER@", () => launcher);
  }
  return rendered;
}

/** package.json's name without its scope, as a program name: what package.nix names the package and its programs. */
function nixPackageName(name) {
  return String(name).split("/").at(-1).toLowerCase().replace(/[^a-z0-9-]/gu, "-");
}

/** What in package-lock.json's packages a build with no network cannot install: each a sentence. */
function lockIssues(packages) {
  const issues = [];
  for (const [key, entry] of Object.entries(packages)) {
    // The root and the workspaces' own folders are the app's source; a bundled package comes inside its parent.
    if (!key.startsWith("node_modules/") && !key.includes("/node_modules/")) continue;
    if (!isObject(entry) || entry.inBundle) continue;
    const resolved = typeof entry.resolved === "string" ? entry.resolved : "";
    if (entry.link) {
      if (path.isAbsolute(resolved) || resolved.split("/")[0] === "..") {
        issues.push(`${key} links to ${resolved}, outside the app, and a build sees only the app's folder: make it one of the ` +
          "app's workspaces, or publish it to a registry.");
      }
    } else if (GIT.test(resolved)) {
      issues.push(`${key} comes from git (${resolved}), and a build with no network fetches only registry tarballs, by their ` +
        "hash: publish it to a registry, or make it one of the app's workspaces.");
    } else if (resolved.startsWith("file:")) {
      issues.push(`${key} is a local file (${resolved}): make it one of the app's workspaces, or publish it to a registry.`);
    } else if (!resolved) {
      issues.push(`${key} has no resolved address in package-lock.json: run npm install to complete the lock file.`);
    } else if (!REMOTE.test(resolved)) {
      issues.push(`${key} comes from ${resolved}, which is not a tarball a build can fetch by its hash.`);
    } else if (typeof entry.integrity !== "string" || !entry.integrity.trim()) {
      issues.push(`${key} has no integrity hash in package-lock.json, and a build fetches each download by its hash: ` +
        "reinstall it (npm install) so that npm records one.");
    }
  }
  return issues;
}

async function readJson(file) {
  try {
    return { value: JSON.parse(await readFile(file, "utf8")) };
  } catch (error) {
    if (error.code === "ENOENT") return { missing: true };
    return { error: `${path.basename(file)} is not JSON: ${error.message}` };
  }
}

/** The app's facts and what keeps package.nix from building it: `manifest` and `lock` issues apart. */
async function analyseApp(projectRoot) {
  const manifest = await readJson(path.join(projectRoot, "package.json"));
  const lock = await readJson(path.join(projectRoot, "package-lock.json"));
  const issues = { manifest: [], lock: [] };
  const app = isObject(manifest.value) ? manifest.value : {};
  if (manifest.missing) issues.manifest.push(`The app has no package.json at ${projectRoot}.`);
  else if (manifest.error) issues.manifest.push(manifest.error);
  else {
    if (typeof app.name !== "string" || !app.name.trim()) {
      issues.manifest.push("package.json has no name: the package and its programs are named after it.");
    }
    if (typeof app.scripts?.start !== "string" || !app.scripts.start.trim()) {
      issues.manifest.push("package.json has no start script: the package's main program runs it, as npm start does.");
    }
  }
  const packages = isObject(lock.value?.packages) ? lock.value.packages : {};
  if (lock.missing) issues.lock.push("The app has no package-lock.json: run npm install to write it, as the package installs what it locks.");
  else if (lock.error) issues.lock.push(lock.error);
  else if (!(Number(lock.value?.lockfileVersion) >= 2) || !isObject(lock.value?.packages)) {
    issues.lock.push(`package-lock.json is lockfileVersion ${lock.value?.lockfileVersion ?? "unknown"}, and the package reads ` +
      "lockfileVersion 2 or 3 (npm 7 and later): run npm install --lockfile-version 3.");
  } else {
    issues.lock.push(...lockIssues(packages));
  }
  const downloads = new Set(Object.values(packages)
    .filter((entry) => isObject(entry) && REMOTE.test(String(entry.resolved ?? "")) && typeof entry.integrity === "string")
    .map((entry) => `${entry.integrity} ${entry.resolved}`));
  const name = nixPackageName(app.name ?? "");
  const programs = [
    { name, does: "[--env FILE] [--migrate]: the start script, from the app's folder, NODE_ENV=production by default; "
      + "with --migrate, db:migrate first when the app has one" },
    { name: `${name}-check`, does: "[--env FILE]: exits 0 once GET /api/health answers 200 on PORT (3000)" },
    { name: `${name}-prepare`, does: "--settings JSON --env FILE [--user NAME]: the settings as an env file for that user, "
      + "and the folders they name for the app's files made for it" },
    ...(typeof app.scripts?.["db:migrate"] === "string" ? [{ name: `${name}-migrate`, does: "[--env FILE]: the db:migrate script" }] : [])
  ];
  return {
    issues,
    name,
    version: typeof app.version === "string" ? app.version : "0.0.0",
    node: /^[^0-9]*([0-9]+)/u.exec(String(app.engines?.node ?? ""))?.[1] ?? null,
    downloads: downloads.size,
    programs
  };
}

async function readPackageNix(projectRoot) {
  try {
    return await readFile(path.join(projectRoot, "package.nix"), "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

/**
 * Writes the app's package.nix unless something keeps it from building the app, or a package.nix it did not write is
 * there. Answers what it found, and `changed` when it wrote the file.
 * @param {{ projectRoot: string }} options
 */
async function packageNix({ projectRoot }) {
  const { issues, ...facts } = await analyseApp(projectRoot);
  const file = path.join(projectRoot, "package.nix");
  const existing = await readPackageNix(projectRoot);
  const refusals = [...issues.manifest, ...issues.lock];
  if (existing !== null && !existing.startsWith(PACKAGE_NIX_MARKER)) {
    refusals.push("package.nix is not one jskit package nix wrote, so it stays: move it away for JSKIT to package the app.");
  }
  if (refusals.length > 0) return { ok: false, issues: refusals, file, changed: false, ...facts };
  const text = renderPackageNix();
  if (existing !== text) await writeFile(file, text);
  return { ok: true, issues: [], file, changed: existing !== text, ...facts };
}

/**
 * Plain `jskit check`'s part: a package.nix that jskit package nix wrote must be this release's, and the app must still
 * build with it. A hand-written package.nix, or none, is left alone.
 * @param {{ projectRoot: string }} options
 */
async function checkPackageNix({ projectRoot }) {
  const existing = await readPackageNix(projectRoot);
  if (existing === null || !existing.startsWith(PACKAGE_NIX_MARKER)) return { ok: true, packaged: false, findings: [] };
  const { issues } = await analyseApp(projectRoot);
  const findings = [
    ...(existing === renderPackageNix() ? [] : [{
      file: "package.nix",
      rule: "package/nix-current",
      message: "package.nix is not the one this JSKIT release writes: run npx jskit package nix."
    }]),
    ...issues.manifest.map((message) => ({ file: "package.json", rule: "package/nix-manifest", message })),
    ...issues.lock.map((message) => ({ file: "package-lock.json", rule: "package/nix-offline", message }))
  ];
  return { ok: findings.length === 0, packaged: true, findings };
}

function formatPackageNixReport(result) {
  if (!result.packaged) return "JSKIT Nix package: none (jskit package nix writes package.nix).";
  const lines = result.findings.flatMap(({ file, rule, message }) => [`${file}  ${rule}  ${message}`, `  ${GUIDE}`]);
  lines.push(result.ok
    ? "JSKIT Nix package: package.nix is current and package-lock.json builds offline."
    : `JSKIT Nix package: ${result.findings.length} error(s); the app's package.nix cannot build it as it is.`);
  return lines.join("\n");
}

export { PACKAGE_NIX_MARKER, checkPackageNix, formatPackageNixReport, nixPackageName, packageNix, renderPackageNix };
